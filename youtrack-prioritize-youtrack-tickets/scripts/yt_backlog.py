def chosen_epic(snap, plan):
    """The epic candidate the plan names, or None when the plan creates one."""
    epic = plan.get("epic") or {}
    if epic.get("action") != "update":
        return None
    for c in snap["epic_candidates"]:
        if c["idReadable"] == epic.get("idReadable"):
            return c
    return None


def _check_field(problems, issue, label, decision, current, allowed):
    d = decision or {}
    state = d.get("decision", "unchanged")
    if state not in FIELD_DECISIONS:
        problems.append(f"{issue}: {label} decision {state!r} is not one of {FIELD_DECISIONS}")
        return
    for key in ("proposed", "approved_value"):
        value = d.get(key)
        if value is not None and value not in allowed:
            problems.append(f"{issue}: {label} {key} {value!r} is not a live allowed value")
    target = d.get("approved_value") or d.get("proposed")
    if state == "approved":
        if not target:
            problems.append(f"{issue}: {label} is approved but names no value; this skill "
                            "never clears a field")
        if not str(d.get("approval") or "").strip():
            problems.append(f"{issue}: {label} is approved with no approval record")
    if state == "unchanged" and target and target != current:
        problems.append(f"{issue}: {label} is marked unchanged but proposes {target!r} "
                        f"over {current!r}; record approved, rejected or pending")


def plan_edges(snap, plan):
    """Confirmed prerequisite pairs (dependent, prerequisite): links plus the plan's own."""
    pairs = {(d["issue"], d["depends_on"]) for d in snap["analysis"]["dependencies"]}
    for it in plan.get("items", []):
        for pre in it.get("after") or []:
            pairs.add((it["issue"], pre))
    return sorted(pairs)


def validate_plan(snap, plan):
    """Every reason this plan must not be applied. An empty list means it may be."""
    problems = []
    short = snap["project"]["shortName"]
    if plan.get("project") != short:
        problems.append(f"plan is for {plan.get('project')!r}, snapshot is for {short!r}")
    if plan.get("snapshot_collected_at") != snap["collected_at"]:
        problems.append("plan was not made from this snapshot (snapshot_collected_at differs)")
    by_id = {i["idReadable"]: i for i in snap["issues"]}
    eligible = set(snap["analysis"]["eligible"])
    items = plan.get("items", [])
    seen = [it.get("issue") for it in items]
    for missing in sorted(eligible - set(seen), key=issue_number):
        problems.append(f"{missing}: eligible but has no rank")
    for extra in sorted(set(seen) - eligible, key=lambda s: issue_number(s or "")):
        problems.append(f"{extra}: ranked but not an eligible ticket of {short}")
    for dup in sorted({s for s in seen if seen.count(s) > 1}):
        problems.append(f"{dup}: ranked more than once")
    ranks = sorted(it.get("rank") for it in items if isinstance(it.get("rank"), int))
    if ranks != list(range(1, len(items) + 1)):
        problems.append(f"ranks must be 1..{len(items)} with no gap or tie")

    hosts = snap["bundles"]["affected_host"]
    priorities = [p for p in snap["bundles"]["priority"] if p in ALLOWED_PRIORITIES]
    conflicts = {c["issue"] for c in snap["analysis"]["parent_conflicts"]}
    rank = {it.get("issue"): it.get("rank") for it in items}
    for it in items:
        issue = it.get("issue")
        cur = by_id.get(issue)
        if not cur:
            continue
        if it.get("readiness") not in READINESS:
            problems.append(f"{issue}: readiness must be one of {READINESS}")
        if not str(it.get("reason") or "").strip():
            problems.append(f"{issue}: no reason recorded")
        _check_field(problems, issue, "Priority", it.get("priority"), cur["priority"], priorities)
        _check_field(problems, issue, "Affected host", it.get("affected_host"),
                     cur["affected_host"], hosts)
        parent = (it.get("parent") or {}).get("decision")
        if issue in conflicts:
            if parent not in ("replace", "keep"):
                problems.append(f"{issue}: already has parent {cur['parent']['idReadable']}; "
                                "the plan must record replace or keep")
            elif parent == "replace" and not str(it["parent"].get("approval") or "").strip():
                problems.append(f"{issue}: replacing its parent has no approval record")

    cyclic = {m for comp in find_cycles(plan_edges(snap, plan)) for m in comp}
    for dependent, pre in plan_edges(snap, plan):
        if dependent in cyclic and pre in cyclic:
            continue
        if dependent in rank and pre in rank and not rank[pre] < rank[dependent]:
            problems.append(f"{dependent} is ranked before its prerequisite {pre}")
    for member in sorted(cyclic & set(rank), key=issue_number):
        it = next(i for i in items if i["issue"] == member)
        if it.get("readiness") != "needs-clarification":
            problems.append(f"{member}: in a dependency cycle, so its readiness must be "
                            "needs-clarification rather than an invented order")

    problems += _validate_epic(snap, plan)
    return problems


def _validate_epic(snap, plan):
    problems = []
    epic = plan.get("epic") or {}
    cands = snap["epic_candidates"]
    mapping = snap["status_mapping"]
    if not cands:
        if epic.get("action") != "create":
            problems.append("no epic exists; the plan must say epic.action = create")
        elif epic.get("status") not in snap["bundles"]["status"] \
                or epic.get("status") in mapping["excluded"]:
            problems.append("epic.status must be a live, open Status value for the new epic")
        elif not str(epic.get("approval") or "").strip():
            problems.append("creating the epic has no approval record")
        if EPIC_TYPE not in snap["bundles"]["type"]:
            problems.append(f"this project has no Type value {EPIC_TYPE!r}")
        return problems
    chosen = chosen_epic(snap, plan)
    if not chosen:
        names = ", ".join(c["idReadable"] for c in cands)
        problems.append(f"the plan must say epic.action = update and name one of: {names}")
        return problems
    if len(cands) > 1 and not str(epic.get("canonical_approval") or "").strip():
        problems.append(f"{len(cands)} issues are named {snap['epic_summary']}; choosing "
                        f"{chosen['idReadable']} has no approval record")
    if isinstance(chosen.get("section"), str) and chosen["section"].startswith("malformed"):
        problems.append(f"{chosen['idReadable']}: {chosen['section']}")
    if chosen["children"] is None:
        problems.append(f"{chosen['idReadable']}: its children could not be read")
    fixes = epic.get("corrections") or {}
    if chosen["type"] != EPIC_TYPE and not str((fixes.get("type") or {}).get("approval") or "").strip():
        problems.append(f"{chosen['idReadable']} has Type {chosen['type']!r}, not Epic; "
                        "the correction needs an approval record")
    if chosen["status_class"] != "open":
        fix = fixes.get("status") or {}
        if fix.get("to") not in snap["bundles"]["status"] or fix.get("to") in mapping["excluded"] \
                or not str(fix.get("approval") or "").strip():
            problems.append(f"{chosen['idReadable']} has Status {chosen['status']!r}; reopening "
                            "it needs an approved, open Status value")
    removals = {r.get("issue"): r for r in plan.get("membership_removals") or []}
    for child in chosen["children"] or []:
        if child["project"] != snap["project"]["shortName"] and child["idReadable"] not in removals:
            problems.append(f"{child['idReadable']} is a child of the epic but belongs to "
                            f"{child['project']}; record a membership_removals decision")
    return problems



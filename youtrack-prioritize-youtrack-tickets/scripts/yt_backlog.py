class Journal:
    """Append-only record of what apply did. A record of intent and outcome,
    never proof: whether a write landed is always decided by reading live state."""

    def __init__(self, path, dry_run=False):
        self.path, self.dry_run, self.entries = path, dry_run, []
        if path and not dry_run:
            os.makedirs(os.path.dirname(os.path.abspath(path)) or ".", exist_ok=True)

    def record(self, op, target, outcome, **detail):
        entry = {"at": now_stamp(), "op": op, "target": target, "outcome": outcome, **detail}
        self.entries.append(entry)
        if self.path and not self.dry_run:
            with open(self.path, "a", encoding="utf-8") as fh:
                fh.write(json.dumps(entry, sort_keys=True) + "\n")
        return outcome


def guarded_write(journal, op, target, is_done, do, **detail):
    """Write once and prove it by reading back.

    is_done() reads live state. It runs before the write (so nothing already in
    place is written again) and after it, whatever the response was: an error or
    a timeout does not mean the write failed, and a 200 does not mean it landed.
    """
    if is_done():
        return journal.record(op, target, "already-in-place", **detail)
    if journal.dry_run:
        return journal.record(op, target, "would-apply", **detail)
    error = None
    try:
        do()
    except Fail as exc:
        error = str(exc)
    try:
        landed = is_done()
    except Fail as exc:
        return journal.record(op, target, "unverified", error=error, read_error=str(exc), **detail)
    if landed:
        return journal.record(op, target, "applied-verified" if not error
                              else "applied-verified-after-error", error=error, **detail)
    return journal.record(op, target, "failed", error=error or "read-back does not match",
                          **detail)


OK_OUTCOMES = ("already-in-place", "applied-verified", "applied-verified-after-error",
               "would-apply")


def read_issue_fields(issue_id):
    return api("GET", f"/api/issues/{issue_id}", {"fields": LIST_FIELDS})


def set_field(issue_id, key, value):
    live = read_issue_fields(issue_id)
    fld = field_map(live).get(key)
    if not fld:
        raise Fail(f"{live.get('idReadable')} has no {FIELDS[key][0]} field")
    api("POST", f"/api/issues/{issue_id}", {"fields": "id"},
        {"customFields": [{"id": fld["id"], "$type": fld["$type"], "value": {"name": value}}]})


def compute_drift(snap, live_snap, plan):
    """What changed since the review. Per-issue drift stops that issue's own
    operations; any drift at all stops the epic description being rewritten."""
    before = {i["idReadable"]: i for i in snap["issues"]}
    after = {i["idReadable"]: i for i in live_snap["issues"]}
    per_issue, general = {}, []
    for rid in sorted(set(before) | set(after), key=issue_number):
        b, a = before.get(rid), after.get(rid)
        notes = []
        if b and not a:
            if b["eligible"]:
                notes.append("no longer in the project")
        elif a and not b:
            if a["eligible"]:
                notes.append("new eligible ticket, not reviewed")
        else:
            for key, label in (("status", "Status"), ("priority", "Priority"),
                               ("affected_host", "Affected host")):
                if b[key] != a[key] and (b["eligible"] or a["eligible"]):
                    notes.append(f"{label} changed {b[key]!r} -> {a[key]!r}")
            bp, ap = (b["parent"] or {}).get("id"), (a["parent"] or {}).get("id")
            if bp != ap and (b["eligible"] or a["eligible"]):
                notes.append("parent changed")
        if notes:
            per_issue[rid] = notes
    b_epics = sorted((c["idReadable"], c["type"], c["status"]) for c in snap["epic_candidates"])
    a_epics = sorted((c["idReadable"], c["type"], c["status"])
                     for c in live_snap["epic_candidates"])
    if b_epics != a_epics:
        general.append(f"epic candidates changed: {b_epics} -> {a_epics}")
    return {"issues": per_issue, "epic": general}


def find_epics(short):
    raw, _ = read_project_issues(short)
    return [r for r in raw if (r.get("summary") or "") == f"{short}{EPIC_SUFFIX}"]


def create_epic(snap, plan, journal):
    """Create the epic only when live state shows none. Returns its entity id or None."""
    short = snap["project"]["shortName"]
    summary = snap["epic_summary"]
    existing = find_epics(short)
    if existing:  # someone, or an earlier attempt, created it since the review
        journal.record("create-epic", summary, "blocked",
                       error=f"{len(existing)} issue(s) with this summary now exist; replan")
        return None
    if journal.dry_run:
        journal.record("create-epic", summary, "would-apply")
        return None
    sample = read_issue_fields(next(i["id"] for i in snap["issues"]))
    fmap = field_map(sample)
    epic = plan["epic"]
    wanted = {"status": {"name": epic["status"]}, "type": {"name": EPIC_TYPE},
              "date_entered": int(time.time() * 1000)}
    if epic.get("assignee"):
        wanted["assignee"] = {"login": epic["assignee"]}
    fields = []
    for key, value in wanted.items():
        if key not in fmap:
            raise Fail(f"{short} has no {FIELDS[key][0]} field to set on the new epic")
        fields.append({"id": fmap[key]["id"], "$type": fmap[key]["$type"], "value": value})
    error = None
    try:
        api("POST", "/api/issues", {"fields": "id,idReadable"},
            {"project": {"id": snap["project"]["id"]}, "summary": summary,
             "customFields": fields})
    except Fail as exc:
        error = str(exc)
    # Never assume a failed response means nothing was created: look.
    found = find_epics(short)
    if not found and error:
        time.sleep(2)
        found = find_epics(short)
    if len(found) == 1:
        journal.record("create-epic", found[0]["idReadable"],
                       "applied-verified" if not error else "applied-verified-after-error",
                       error=error)
        return found[0]["id"]
    journal.record("create-epic", summary, "failed",
                   error=error or f"{len(found)} issues with this summary after the create")
    return None


def ancestors(issue_id, limit=50):
    out, current = [], issue_id
    for _ in range(limit):
        parent = parent_of(api("GET", f"/api/issues/{current}", {"fields": "parent(issues(id))"}))
        if not parent or parent["id"] in out:
            return out
        out.append(parent["id"])
        current = parent["id"]
    raise Fail("parent chain is deeper than expected; refusing to guess about cycles")


def live_parent_id(issue_id):
    parent = parent_of(api("GET", f"/api/issues/{issue_id}", {"fields": "parent(issues(id))"}))
    return parent["id"] if parent else None


def apply(snap, plan, journal_path, dry_run=False):
    problems = validate_plan(snap, plan)
    if problems:
        raise Fail("the plan is not valid, nothing was written:\n  " + "\n  ".join(problems))
    journal = Journal(journal_path, dry_run)
    short = snap["project"]["shortName"]
    project = {"id": snap["project"]["id"], "shortName": short, "name": snap["project"]["name"]}

    # Recheck before writing: the review is only as good as the state it saw.
    live_snap = collect(project, deep=False)
    drift = compute_drift(snap, live_snap, plan)
    live = {i["idReadable"]: i for i in live_snap["issues"]}
    stale = drift["issues"]
    epic_blocked = list(drift["epic"])
    result = {"field_changes": [], "added": [], "removed": [], "membership_incomplete": {},
              "skipped": [], "reviewed_at": now_stamp()}

    # 1. Field changes: approved ones only, and only where nothing moved.
    for it in _items(plan):
        rid = it["issue"]
        for key, label in (("priority", "Priority"), ("affected_host", "Affected host")):
            d = it.get(key) or {}
            if d.get("decision") != "approved":
                continue
            target = d.get("approved_value") or d.get("proposed")
            if rid in stale:
                journal.record("set-field", rid, "skipped-stale", field=label,
                               reason="; ".join(stale[rid]))
                result["skipped"].append(f"{rid} {label}: changed since review")
                continue
            entity = live[rid]["id"]
            outcome = guarded_write(
                journal, "set-field", rid,
                lambda e=entity, k=key, t=target: field_value(read_issue_fields(e), k) == t,
                lambda e=entity, k=key, t=target: set_field(e, k, t),
                field=label, value=target, approval=d.get("approval"))
            if outcome in ("applied-verified", "applied-verified-after-error", "would-apply"):
                result["field_changes"].append(f"{rid} {label} -> {target}")

    # 2. The epic itself.
    epic_id = None
    epic_plan = plan["epic"]
    if not epic_blocked:
        if epic_plan["action"] == "create":
            epic_id = create_epic(snap, plan, journal)
            if not epic_id and not dry_run:
                epic_blocked.append("the epic could not be created or confirmed")
        else:
            chosen = chosen_epic(snap, plan)
            epic_id = chosen["id"]
            fixes = epic_plan.get("corrections") or {}
            if chosen["type"] != EPIC_TYPE:
                outcome = guarded_write(
                    journal, "set-field", chosen["idReadable"],
                    lambda: field_value(read_issue_fields(epic_id), "type") == EPIC_TYPE,
                    lambda: set_field(epic_id, "type", EPIC_TYPE), field="Type", value=EPIC_TYPE)
                if outcome not in OK_OUTCOMES:
                    epic_blocked.append("the epic's Type could not be corrected")
            if chosen["status_class"] != "open":
                to = fixes["status"]["to"]
                outcome = guarded_write(
                    journal, "set-field", chosen["idReadable"],
                    lambda: field_value(read_issue_fields(epic_id), "status") == to,
                    lambda: set_field(epic_id, "status", to), field="Status", value=to)
                if outcome not in OK_OUTCOMES:
                    epic_blocked.append("the epic's Status could not be corrected")

    # 3. Membership.
    if epic_id and not epic_blocked:
        types = link_types()
        link_id = subtask_link_id(epic_id, types)
        epic_ancestors = ancestors(epic_id)
        children = read_children(epic_id, types, live_snap["status_mapping"])
        removals = {r["issue"]: r for r in plan.get("membership_removals") or []}
        for child in children:
            cid, rid = child["id"], child["idReadable"]
            foreign = child["project"] != short
            if foreign:
                if (removals.get(rid) or {}).get("decision") != "approved":
                    result["skipped"].append(f"{rid}: cross-project child left in place, "
                                             "removal not approved")
                    continue
            elif child["status_class"] not in ("done", "do-not-do"):
                continue  # still open, or Status unreadable: keep it and say so elsewhere
            outcome = guarded_write(
                journal, "remove-child", rid,
                lambda c=cid: live_parent_id(c) != epic_id,
                lambda c=cid: api("DELETE", f"/api/issues/{epic_id}/links/{link_id}/issues/{c}"),
                reason="cross-project" if foreign else child["status"])
            if outcome in ("applied-verified", "applied-verified-after-error", "would-apply"):
                result["removed"].append(rid)
        for it in _items(plan):
            rid = it["issue"]
            if rid in stale:
                journal.record("add-child", rid, "skipped-stale", reason="; ".join(stale[rid]))
                result["membership_incomplete"][rid] = "changed since review"
                continue
            cur = live[rid]
            if cur["id"] == epic_id or cur["id"] in epic_ancestors:
                journal.record("add-child", rid, "blocked", reason="would create a hierarchy cycle")
                result["membership_incomplete"][rid] = "would create a hierarchy cycle"
                continue
            parent = cur["parent"]
            if parent and parent["id"] != epic_id \
                    and (it.get("parent") or {}).get("decision") != "replace":
                journal.record("add-child", rid, "skipped-not-approved",
                               reason=f"existing parent {parent['idReadable']} kept")
                result["membership_incomplete"][rid] = f"existing parent {parent['idReadable']}"
                continue
            outcome = guarded_write(
                journal, "add-child", rid,
                lambda c=cur["id"]: live_parent_id(c) == epic_id,
                lambda c=cur["id"]: api("POST", f"/api/issues/{epic_id}/links/{link_id}/issues",
                                        {"fields": "id"}, {"id": c}))
            if outcome in ("applied-verified", "applied-verified-after-error", "would-apply"):
                result["added"].append(rid)
            elif outcome != "already-in-place":
                result["membership_incomplete"][rid] = "link write failed"
    elif dry_run and not epic_blocked:
        # The epic does not exist yet, so list what a real run would link to it.
        for it in _items(plan):
            rid = it["issue"]
            parent = live[rid]["parent"] if rid in live else None
            if rid in stale:
                result["membership_incomplete"][rid] = "changed since review"
            elif parent and (it.get("parent") or {}).get("decision") != "replace":
                result["membership_incomplete"][rid] = f"existing parent {parent['idReadable']}"
            else:
                journal.record("add-child", rid, "would-apply")
                result["added"].append(rid)
    else:
        for it in _items(plan):
            result["membership_incomplete"].setdefault(it["issue"], "epic operations blocked")

    # 4. The description: only when the ranked list still describes what is there.
    description_state = "not-written"
    if stale or epic_blocked:
        why = "; ".join(epic_blocked) or "tickets changed since review"
        journal.record("write-description", snap["epic_summary"], "blocked", reason=why)
        description_state = f"blocked: {why}"
    elif epic_id:
        fresh = collect(project, deep=False)
        now_live = {i["idReadable"]: i for i in fresh["issues"]}
        section = render_section(snap, plan, now_live, result)
        current = read_issue_fields(epic_id).get("description") or ""
        wanted = splice_section(current, section)  # raises on malformed markers
        if outside_section(wanted) != outside_section(current):
            raise Fail("refusing to write: text outside the generated section would change")
        outcome = guarded_write(
            journal, "write-description", snap["epic_summary"],
            lambda: (read_issue_fields(epic_id).get("description") or "").replace("\r\n", "\n")
            == wanted,
            lambda: api("POST", f"/api/issues/{epic_id}", {"fields": "id"},
                        {"description": wanted}))
        description_state = outcome
    elif dry_run:
        description_state = journal.record("write-description", snap["epic_summary"], "would-apply")

    failures = [e for e in journal.entries if e["outcome"] in ("failed", "unverified")]
    epic_readable = None
    if epic_id:
        epic_readable = read_issue_fields(epic_id).get("idReadable")
    report = {
        "project": short, "dry_run": dry_run,
        "epic": epic_readable, "epic_url": issue_url(epic_readable) if epic_readable else None,
        "reviewed": len(plan["items"]), "next_actionable": plan.get("next_actionable", []),
        "field_changes": result["field_changes"], "children_added": result["added"],
        "children_removed": result["removed"],
        "membership_incomplete": result["membership_incomplete"],
        "description": description_state,
        "drift": drift, "epic_blocked": epic_blocked, "skipped": result["skipped"],
        "failures": failures, "journal": journal_path,
        "pending_decisions": [f"{it['issue']} {label}"
                              for it in _items(plan)
                              for key, label in (("priority", "Priority"),
                                                 ("affected_host", "Affected host"))
                              if (it.get(key) or {}).get("decision") == "pending"],
    }
    report["complete"] = not (failures or stale or epic_blocked
                              or result["membership_incomplete"])
    return report


# ------------------------------------------------------------------ read-issue

def read_issue(readable):
    raw = api("GET", f"/api/issues/{readable}", {"fields": LIST_FIELDS})
    out = {"id": raw["id"], "idReadable": raw["idReadable"], "url": issue_url(raw["idReadable"]),
           "project": (raw.get("project") or {}).get("shortName"),
           "summary": raw.get("summary"), "description": raw.get("description") or "",
           "status": field_value(raw, "status"), "priority": field_value(raw, "priority"),
           "affected_host": field_value(raw, "affected_host"), "parent": parent_of(raw)}
    out["links"] = read_links(raw["id"])
    out["comments"] = read_comments(raw["id"])
    return out


# ------------------------------------------------------------------------- CLI

def _load(path):
    with open(os.path.expanduser(path), encoding="utf-8") as fh:
        return json.load(fh)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("resolve-project").add_argument("project")
    p = sub.add_parser("collect")
    p.add_argument("project"); p.add_argument("out")
    sub.add_parser("read-issue").add_argument("issue")
    for name in ("validate-plan", "render-section"):
        p = sub.add_parser(name)
        p.add_argument("snapshot"); p.add_argument("plan")
    p = sub.add_parser("review-table")
    p.add_argument("snapshot"); p.add_argument("plan")
    p.add_argument("--batch-size", type=int, default=25)
    p = sub.add_parser("apply")
    p.add_argument("snapshot"); p.add_argument("plan")
    p.add_argument("--journal", required=True, help="append-only record of this apply")
    p.add_argument("--dry-run", action="store_true", help="list the operations, write nothing")
    args = ap.parse_args(argv)

    try:
        if args.cmd == "resolve-project":
            print(json.dumps(resolve_project(args.project), indent=2))
        elif args.cmd == "collect":
            snap = collect(resolve_project(args.project))
            out = os.path.expanduser(args.out)
            os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
            with open(out, "w", encoding="utf-8") as fh:
                json.dump(snap, fh, indent=2, sort_keys=True)
            print(f"Wrote {out}")
            print(json.dumps({k: snap["analysis"][k] for k in
                              ("counts", "status_unknown", "cycles", "parent_conflicts",
                               "epic_state", "incomplete_reads")}, indent=2))
            print(f"Eligibility: {snap['status_mapping']['rule']}")
        elif args.cmd == "read-issue":
            print(json.dumps(read_issue(args.issue.strip().rsplit("/", 1)[-1]), indent=2))
        elif args.cmd == "validate-plan":
            problems = validate_plan(_load(args.snapshot), _load(args.plan))
            for prob in problems:
                print(f"FAIL: {prob}")
            if problems:
                return 1
            print("OK: the plan covers every eligible ticket and every write has an approval")
        elif args.cmd == "review-table":
            print(review_table(_load(args.snapshot), _load(args.plan), args.batch_size))
        elif args.cmd == "render-section":
            print(render_section(_load(args.snapshot), _load(args.plan)))
        elif args.cmd == "apply":
            report = apply(_load(args.snapshot), _load(args.plan),
                           os.path.expanduser(args.journal), args.dry_run)
            print(json.dumps(report, indent=2))
            return 0 if report["complete"] else 3
    except Fail as exc:
        sys.stdout.flush()
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
